async function main() {
  console.log("Seeding blog categories...");

  for (const cat of categories) {
    await db.blogCategory.upsert({
      where: { slug: cat.slug },
      update: {},
      create: cat,
    });
    console.log(`  ✓ Category: ${cat.name}`);
  }

  console.log("\nSeeding blog posts...");

  for (const post of posts) {
    const cat = await db.blogCategory.findUnique({ where: { slug: post.category } });
    if (!cat) {
      console.error(`  ✗ Category not found: ${post.category}`);
      continue;
    }

    await db.blogPost.upsert({
      where: { slug: post.slug },
      update: {},
      create: {
        title: post.title,
        slug: post.slug,
        excerpt: post.excerpt,
        body: post.body,
        categoryId: cat.id,
        status: "PUBLISHED",
        author: "تیم لیان دیزاین",
      },
    });
    console.log(`  ✓ ${post.title}`);
  }

  const count = await db.blogPost.count();
  console.log(`\nBlog seed complete! Total posts: ${count}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });
